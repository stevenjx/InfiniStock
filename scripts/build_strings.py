def build():
    root = pathlib.Path(__file__).resolve().parent.parent
    catalog_path = root / "InfiniStock" / "Localizable.xcstrings"
    catalog = json.loads(catalog_path.read_text(encoding="utf-8"))

    added = 0
    for zh, en in T.items():
        entry = catalog["strings"].setdefault(zh, {})
        entry["extractionState"] = "manual"
        locs = entry.setdefault("localizations", {})
        locs["zh-Hans"] = {"stringUnit": {"state": "translated", "value": zh}}
        locs["en"] = {"stringUnit": {"state": "translated", "value": en}}
        added += 1

    for zh in SKIP:
        entry = catalog["strings"].setdefault(zh, {})
        entry["extractionState"] = "manual"
        # 标成不需要翻译：中英都留原文，避免出现空译文
        locs = entry.setdefault("localizations", {})
        locs["zh-Hans"] = {"stringUnit": {"state": "translated", "value": zh}}
        locs["en"] = {"stringUnit": {"state": "translated", "value": zh}}

    catalog_path.write_text(
        json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(f"写入 {added} 条翻译，{len(SKIP)} 条保留原文，catalog 共 {len(catalog['strings'])} 条")

if __name__ == "__main__":
    build()
